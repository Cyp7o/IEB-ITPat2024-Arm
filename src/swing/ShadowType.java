// Define the package that this class belongs to
package swing;

// Declaration of an enum named ShadowType
public enum ShadowType {
    // Enum constants representing different types of shadow positions
    CENTER, // No specific shadow direction, centered shadow
    TOP_RIGHT, // Shadow positioned at the top-right corner
    TOP_LEFT, // Shadow positioned at the top-left corner
    BOT_RIGHT, // Shadow positioned at the bottom-right corner
    BOT_LEFT, // Shadow positioned at the bottom-left corner
    BOT, // Shadow positioned at the bottom
    TOP;         // Shadow positioned at the top
}
