    private void btnViewProperty1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewProperty1ActionPerformed
        // TODO add your handling code here:
        // Get the row number of the selected property from the table
        int rowSelected = tblProperties.getSelectedRow();

        // Check if a property is selected in the table.
        if (rowSelected == -1) {
            JOptionPane.showMessageDialog(null, "Please select a property to view");
        } else {
            // Retrieve property details from the selected row in the table.
            int propertyID = (int) tblProperties.getValueAt(rowSelected, 0);
            String suburb = (String) tblProperties.getValueAt(rowSelected, 1);
            String complex = (String) tblProperties.getValueAt(rowSelected, 2);
            String UnitNo = (String) tblProperties.getValueAt(rowSelected, 3);
            String adress = (String) tblProperties.getValueAt(rowSelected, 4);
            String category = (String) tblProperties.getValueAt(rowSelected, 5);
            int bedrooms = (int) tblProperties.getValueAt(rowSelected, 6);
            double bathrooms = (double) tblProperties.getValueAt(rowSelected, 7);
            boolean occupied = (boolean) tblProperties.getValueAt(rowSelected, 8);
            int rent = (int) tblProperties.getValueAt(rowSelected, 9);
            String image = (String) tblProperties.getValueAt(rowSelected, 10);

            // Create a Property instance with the selected property details.
            propertySelected = new Property(propertyID,suburb,complex, UnitNo,adress,category,bedrooms, bathrooms, occupied, rent , image);

            // Get the owner details for the selected property.
            TenantManager Tm = new  TenantManager();
            tenantSelected = Tm.getTenant(propertyID);

            // Open the ViewPropertyScreen and pass the property and owner details.
            new ViewPropertyScreen(propertySelected, tenantSelected, false, false).setVisible(true);
           this.dispose();
        }
    }//GEN-LAST:event_btnViewProperty1ActionPerformed

