    private void btnDeletePropertyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeletePropertyActionPerformed
     // Get the row number of the selected property from the table
        int rowSelected = tblProperties.getSelectedRow();

        // Check if a row is selected in the table
        if (rowSelected == -1) {
            // If no row is selected, show an error message to the user
            JOptionPane.showMessageDialog(null, "Please select a property to delete");
        } else {
            // If a row is selected, get the property ID of the selected property
            int propertyID = (int) tblProperties.getValueAt(rowSelected, 0);

            // Show a confirmation dialog to the user to confirm the deletion
            int confirmation = JOptionPane.showConfirmDialog(PropertyScreen.this, "Are you sure you want to delete this property?", "Deletion Confirmation", JOptionPane.YES_NO_OPTION);

            // If the user confirms the deletion
            if (confirmation == JOptionPane.YES_OPTION) {
                // Delete the property using the PropertyManager
                PropertyManager pm = new PropertyManager();
                pm.deleteProperty(propertyID);

                // Update the table to reflect the changes
                pm.addSearchedDataToTable((DefaultTableModel) tblProperties.getModel(), "");

                // Show a success message to the user
                JOptionPane.showMessageDialog(null, "Property has been deleted");
            }
        }
    }//GEN-LAST:event_btnDeletePropertyActionPerformed

