    private void textFieldSearchOptionKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_textFieldSearchOptionKeyReleased
         // Check if the search option is selected
        if (textFieldSearchOption.isSelected()) {
            // Get the index of the selected search option
            int option = textFieldSearchOption.getSelectedIndex();

            // Get the text entered in the search field and add '%' to enable partial matching
            String text = "%" + textFieldSearchOption.getText().trim() + "%";

            // Create a new PropertyManager to handle the search operation
            PropertyManager pm = new PropertyManager();

            // Use a switch statement to perform the search based on the selected option
            switch (option) {
                case 0:
                    // Search for properties where PropertyID matches the entered text
                    pm.addSearchedDataToTable((DefaultTableModel) tblProperties.getModel(), "WHERE PropertyID LIKE ?", text);
                    break;
                case 1:
                    // Search for properties where Address matches the entered text
                    pm.addSearchedDataToTable((DefaultTableModel) tblProperties.getModel(), "WHERE Address LIKE ?", text);
                    break;
                case 2:
                    // Search for properties where Suburb matches the entered text
                    pm.addSearchedDataToTable((DefaultTableModel) tblProperties.getModel(), "WHERE Suburb LIKE ?", text);
                    break;
                case 3:
                    // Search for properties where PropertyType matches the entered text
                    pm.addSearchedDataToTable((DefaultTableModel) tblProperties.getModel(), "WHERE Category LIKE ?", text);
                    break;
                case 4:
                    // Search for properties where Bedrooms matches the entered text
                    pm.addSearchedDataToTable((DefaultTableModel) tblProperties.getModel(), "WHERE Bedrooms LIKE ?", text);
                    break;
                case 5:
                    // Search for properties where Bathrooms matches the entered text
                    pm.addSearchedDataToTable((DefaultTableModel) tblProperties.getModel(), "WHERE Bathrooms LIKE ?", text);
                    break;
                default:
                    // If no option is selected, do nothing
                    break;
            }
        }
    }//GEN-LAST:event_textFieldSearchOptionKeyReleased

