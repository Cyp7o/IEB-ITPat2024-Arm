    private void MailbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_MailbtnActionPerformed

        Desktop desktop;
        if (Desktop.isDesktopSupported()
            && (desktop = Desktop.getDesktop()).isSupported(Desktop.Action.MAIL)) {
            try {
                URI mailto = new URI("mailto:your-email@example.com?subject=Apartment%20rental%20manemgment%20support:");
                desktop.mail(mailto);
            } catch (URISyntaxException ex) {
                Logger.getLogger(SplashScreen.class.getName()).log(Level.SEVERE, null, ex);
            } catch (IOException ex) {
                Logger.getLogger(SplashScreen.class.getName()).log(Level.SEVERE, null, ex);
            }
        } else {
            // TODO fallback to some Runtime.exec(..) voodoo?
            throw new RuntimeException("desktop doesn't support mailto; mail is dead anyway ;)");
        }
    }//GEN-LAST:event_MailbtnActionPerformed

    private void bntForgotPassActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bntForgotPassActionPerformed
  // Prompt the user to enter their username
String username = JOptionPane.showInputDialog(null, "Please enter your username:");

// Check if the username is null or empty
if (username == null || username.isEmpty()) {
    // Show an error message if the username is not provided
    JOptionPane.showMessageDialog(null, "Username cannot be empty.");
    return; // Exit the method if the username is invalid
}

// Prepare the email subject by encoding the username with a specific message
String subject = null;
        try {
            subject = URLEncoder.encode(username + " forgot password", "UTF-8");
        } catch (UnsupportedEncodingException ex) {
            Logger.getLogger(LoginScreen.class.getName()).log(Level.SEVERE, null, ex);
        }

// Prepare the email body with device and Java version information
String body = "Operating System: " + System.getProperty("os.name") + " "
        + System.getProperty("os.version") + " (" + System.getProperty("os.arch") + ")\n"
        + "Java Version: " + System.getProperty("java.version");

// Encode the email body for inclusion in the mailto URI
String encodedBody = null;
        try {
            encodedBody = URLEncoder.encode(body, "UTF-8");
        } catch (UnsupportedEncodingException ex) {
            Logger.getLogger(LoginScreen.class.getName()).log(Level.SEVERE, null, ex);
        }

// Construct the mailto URI with the recipient email address, subject, and body
String uriString = "mailto:your-email@example.com" + "?subject=" + subject + "&body=" + encodedBody;

// Attempt to open the default email client with the constructed mailto URI
try {
    URI mailtoUri = new URI(uriString); // Create a URI object from the string
    java.awt.Desktop.getDesktop().mail(mailtoUri); // Open the default email client with the mailto URI
} catch (IOException | URISyntaxException e) {
    // Log the exception and show an error message if opening the email client fails
    Logger.getLogger(HomeScreen.class.getName()).log(Level.SEVERE, null, e);
    JOptionPane.showMessageDialog(null, "Failed to open email client.");
}
      
    }//GEN-LAST:event_bntForgotPassActionPerformed

