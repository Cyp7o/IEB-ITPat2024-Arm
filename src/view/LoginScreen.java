    private void SigninbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SigninbtnActionPerformed
 // Get the email and password entered by the user
        String email = txtEmail.getText();
        String password = new String(txtPassword.getPassword());

        // Create an instance of CredentialsManager to handle user login details
        CredentialsManager ldm = new CredentialsManager();

        // Check if the provided login details are valid
        if (ldm.checkLoginDetails(email, password)) {
            // Get the username and profile picture associated with the email
            String username = ldm.getUsername(email);
            String profilePic = ldm.getProfilePic(email);

            // Create a Credentials object to store the user's details
            userSelected = new Credentials(username, profilePic);

            // Successful login, open the home screen and close the login screen
           // new HomeScreen().setVisible(true);
            new HomeScreen().setVisible(true);
            this.dispose();
        } else {
            // Invalid credentials, display an error message
            JOptionPane.showMessageDialog(this, "Invalid email or password", "Login Failed", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_SigninbtnActionPerformed

